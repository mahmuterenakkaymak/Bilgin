"""Read-only MSSQL login script (PLAN R3-8).

The Python policy allowlist reads the table names a query mentions; a VIEW, SYNONYM or
table-valued function can wrap a table that is not on the allowlist, and the parser only ever
sees the wrapper's name, never the table behind it. So the durable boundary is a database
permission, not the parser: the login below can read only the allowlisted tables and can never
see a PII column. The script is generated by ``python -m nl2sql make-login-script``; it is not
edited by hand.

Every DENY is emitted as dynamic SQL (``EXEC('DENY ...')``) because sqlglot - the tool that
validates this script parses - has no grammar for a bare DENY statement; the string keeps the
whole script parseable while the statement stays exactly what a DBA would run.
"""

from __future__ import annotations

from nl2sql.policy import pii
from nl2sql.schema_map import doc

DEFAULT_LOGIN = "nl2sql_ro"
PASSWORD_PLACEHOLDER = "__DEGISTIR__"
# ASSUMPTION: every table in the schema (PII columns included) lives in the default dbo schema,
# as it does in a Netsis database; the cursor reads each owner from sys.tables, the explicit
# column DENYs below name dbo directly.
OWNER = "dbo"


def readonly_login_sql(schema: dict, login: str) -> str:
    """T-SQL for a read-only login: db_datareader, then DENY over non-allowlist tables and PII columns.

    ``schema`` is the loaded schema doc; its table names are the allowlist and its ``pii`` marks
    are the columns denied at column level. The password is always the placeholder - never a real
    secret - so the generated file is safe to keep in the repository.
    """
    tables = sorted(doc.allowlist(schema))
    parts = [
        _header(login),
        _principal(login),
        _deny_other_tables(login, tables),
        _deny_pii_columns(login, schema),
        _deny_definition(login),
    ]
    return "\nGO\n\n".join(parts) + "\n"


def _header(login: str) -> str:
    return (
        "-- Bu dosya `python -m nl2sql make-login-script` ile üretilir; elle düzenlemeyin.\n"
        f"-- Salt okunur giriş: [{login}] — betiği hedef veritabanı bağlamında çalıştırın.\n"
        "--\n"
        "-- Bu betik birincil kontroldür. Python tarafındaki politika allowlist'i sorgudaki tablo\n"
        "-- adlarını denetler; oysa bir VIEW, SYNONYM ya da tablo değerli işlev (TVF) allowlist'te\n"
        "-- olmayan bir tablonun üstünü sarabilir ve sorgu yalnızca kapsayıcının adını yazdığı için\n"
        "-- parser bunu hiç görmez. Kalıcı sınır burada: giriş yalnız allowlist'teki tabloları okur,\n"
        "-- hiçbir PII kolonunu hiç göremez ve hiçbir yordamı çalıştıramaz. DENY, GRANT'ı (db_datareader\n"
        "-- dahil) yener."
    )


def _principal(login: str) -> str:
    return (
        f"-- 1) Sunucu girişi ve veritabanı kullanıcısı (parolayı {PASSWORD_PLACEHOLDER} yerine koyun).\n"
        f"CREATE LOGIN [{login}] WITH PASSWORD = '{PASSWORD_PLACEHOLDER}';\n"
        f"CREATE USER [{login}] FOR LOGIN [{login}];\n"
        f"ALTER ROLE db_datareader ADD MEMBER [{login}];"
    )


def _deny_other_tables(login: str, tables: list[str]) -> str:
    allowed = ", ".join(f"'{name}'" for name in tables)
    return (
        "-- 2) Allowlist'te olmayan her tablodan SELECT reddedilir (db_datareader'ı geri alır).\n"
        "DECLARE @sql nvarchar(max);\n"
        "DECLARE cur CURSOR LOCAL FAST_FORWARD FOR\n"
        f"SELECT 'DENY SELECT ON ' + QUOTENAME(SCHEMA_NAME(schema_id)) + '.' + QUOTENAME(name) + ' TO [{login}]'\n"
        "FROM sys.tables\n"
        f"WHERE name NOT IN ({allowed});\n"
        "OPEN cur;\n"
        "FETCH NEXT FROM cur INTO @sql;\n"
        "WHILE @@FETCH_STATUS = 0\n"
        "BEGIN\n"
        "    EXEC (@sql);\n"
        "    FETCH NEXT FROM cur INTO @sql;\n"
        "END;\n"
        "CLOSE cur;\n"
        "DEALLOCATE cur;"
    )


def _deny_pii_columns(login: str, schema: dict) -> str:
    columns: dict[str, list[str]] = {}
    for table, column in pii.column_map(schema):
        columns.setdefault(table, []).append(column)
    lines = ["-- 3) PII kolonları: tablo okunabilse bile bu kolonlar hiç seçilemez."]
    for table in sorted(columns):
        cols = ", ".join(sorted(columns[table]))
        lines.append(f"EXEC('DENY SELECT ({cols}) ON [{OWNER}].[{table}] TO [{login}]');")
    return "\n".join(lines)


def _deny_definition(login: str) -> str:
    return (
        "-- 4) Tanım görme ve yordam çalıştırma yok (TVF/SYNONYM yan kanalını da kapatır).\n"
        f"EXEC('DENY VIEW DEFINITION TO [{login}]');\n"
        f"EXEC('DENY EXECUTE TO [{login}]');"
    )
